export function poolPlan(phase, slot) {
  const calm = (min, say) => ({ text: `${min} мин спокойного плавания`, segments: [{ label: 'Спокойно', sec: min * 60, every: 300, say }] });
  if (slot === 'cardio') return phase === 'deload' ? calm(20, 'Лёгкое плавание, 20 минут') : calm(30, 'Плаваем 30 минут. Сигнал каждые 5 минут');
  if (phase === 'deload') return calm(20, 'Лёгкое плавание, 20 минут');
  if (phase === 'p1') {
    return { text: '20–30 мин спокойно, остановки не дольше 30 с', segments: [{ label: 'Спокойно', sec: 25 * 60, every: 300, say: 'Плаваем 25 минут. Сигнал каждые 5 минут' }] };
  }
  const n = phase === 'p2' ? 4 : 6;
  const segments = [];
  for (let i = 1; i <= n; i++) {
    const last = i === n ? 'Последний интервал. ' : '';
    segments.push({ label: `Бодро · ${i} из ${n}`, sec: 120, say: `${last}Интервал ${i} из ${n}. Бодро, 2 минуты`, beep: 'brisk' });
    segments.push({ label: `Спокойно · ${i} из ${n}`, sec: 60, say: 'Спокойно, минута', beep: 'easy' });
  }
  return { text: `${n} × (2 мин бодро + 1 мин спокойно)`, segments };
}

